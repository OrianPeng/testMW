// 翻译函数
function translateFile(filePath) {
  try {
    let content = fs.readFileSync(filePath, 'utf8');
    let hasChanges = false;
    
    // 执行翻译
    Object.keys(finalTranslations).forEach(chinese => {
      const english = finalTranslations[chinese];
      const regex = new RegExp(chinese.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
      const newContent = content.replace(regex, english);
      if (newContent !== content) {
        content = newContent;
        hasChanges = true;
      }
    });
    
    if (hasChanges) {
      fs.writeFileSync(filePath, content, 'utf8');
      console.log(`✅ ${filePath} translated successfully`);
    } else {
      console.log(`ℹ️  ${filePath} no changes needed`);
    }
  } catch (error) {
    console.error(`❌ Error translating ${filePath}:`, error.message);
  }
}

// 翻译所有文件
